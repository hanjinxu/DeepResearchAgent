"""
记忆层共 3 个 prompt：
1. EVENT_KEY_EXTRACT_PROMPT —— 从 query 抽 (subject, issue, aliases)，供 L1 精确匹配与 event_id 生成
2. EVENT_DEDUP_JUDGE_PROMPT —— L3 LLM 判定：当前 query 与历史候选是否同一事件
3. DELTA_EXTRACT_PROMPT     —— 从增量检索结果中抽「传闻状态迁移」+「新时间线节点」

本项目统一约定：不用 response_format，直接调用模型后手动解析 JSON
（见 draft_agent.py 的既有做法，DeepSeek 不支持 response_format）。
"""


# ===== 1. 事件主体 / 议题抽取 =====

EVENT_KEY_EXTRACT_PROMPT = """你是舆情事件的实体抽取器。请从下面这条"热点事件查询"中，抽出**事件主体**和**事件议题**。

# 抽取规则
1. `subject`（事件主体）：只保留最核心的机构名 / 人名 / 产品名，不要带修饰语和情绪词。
   - "华为余承东竹知了事件" → subject = "华为余承东"
   - "小米SU7 碰撞事故" → subject = "小米SU7"
   - "某明星偷税被举报" → subject = "该明星姓名"（若未指名，填最核心的可识别主体）
2. `issue`（事件议题）：用 4~12 个字概括"到底发生了什么"，去掉"事件 / 风波 / 舆情 / 热搜"这类空词。
   - "华为余承东竹知了事件" → issue = "竹知了"
   - "内部推荐政策被质疑" → issue = "内部推荐政策"
3. `aliases`（主体别名/简称）：最多 3 个，供后续精确匹配使用；没有就返回空数组。
   - "华为余承东" → ["余承东", "华为"]

# 当前查询
{query}

# 输出（只输出 JSON，不要解释、不要代码块标记）
{{"subject": "...", "issue": "...", "aliases": ["..."]}}
"""


# ===== 2. L3 同事件判定 =====

EVENT_DEDUP_JUDGE_PROMPT = """你是舆情事件归并判定器。请判断「当前查询」与「候选历史事件」是否为**同一个事件的同一个议题**。

# 判定标准
- **同一事件** = 主体相同（含别名 / 简称 / 同一人的不同称呼）+ 议题指向同一件事。
- 主体相同、议题是**同一件事的不同阶段或不同说法** → 判为同一事件（is_same = true）。
  - 「余承东竹知了事件」 vs 「余承东 竹知了 最新回应」 → 同一事件
  - 「华为内部推荐政策」 vs 「华为 内推政策 争议」 → 同一事件
- 以下判为**不同事件**（is_same = false）：
  - 主体相同但议题完全无关（同一家公司的两起不同事件）
  - 主体不同（即使是同行业的同类事件）
- ⚠️ 拿不准时**倾向 is_same = false**：宁可新开一条记录，也不要错误合并——
  合并错误会把不相干的历史基线污染进当前报告的上下文。

# 候选历史事件
{candidates}

# 当前查询
{query}

# 输出（只输出 JSON，不要解释、不要代码块标记）
{{"is_same": true, "matched_event_id": "命中的 event_id，没命中则填空字符串", "confidence": 0.85, "reason": "一句话判定理由"}}
"""


# ===== 3. 增量进展抽取（传闻状态机 + 时间线） =====

DELTA_EXTRACT_PROMPT = """你是舆情进展追踪器。下面给出【历史事件基线】和【本次检索到的最新资料】。
请**只提取相对历史基线而言的新信息**，不要重复已知内容。

# 任务 A：更新传闻状态机（对应报告骨架 2.2 节）
对照历史基线中的「已知传闻状态机」，判断本次资料是否**证实或证伪**了某条传闻：
- 出现了**官方声明 / 当事人承认 / 权威媒体核实报道** → 可升级为 `confirmed` 或 `refuted`
- 只有自媒体转述、无一手来源 → 维持 `unconfirmed`，**不要擅自升级**
- 输出 `rumor_updates`，每项格式：
  {{"target": "历史传闻的原文（必须与基线列表中的文字基本一致，用于定位）",
    "new_status": "confirmed|refuted|partially_confirmed|unconfirmed",
    "confidence": "低|中|高",
    "evidence": ["来源URL或关键引文"],
    "reason": "为什么这样判定"}}
- 若本次资料提出了**全新的传闻**（基线里没有），也放进 `rumor_updates`，
  `target` 填新传闻原文，`new_status` 填 `unconfirmed`。

# 任务 B：抽取新的时间线节点（对应报告骨架 1.2 节）
只抽取带**明确时间点**且**历史基线里没有**的事件进展：
- "2026-06-15 华为发布内部邮件回应" → 抽为新节点
- 时间能到天就到天、能到小时就到小时；模糊表述（"近日""前段时间"）一律不抽
- 输出 `timeline_updates`，每项格式：
  {{"time": "2026-06-15", "node": "华为发布内部邮件回应", "source": "URL或信源名"}}

# 硬性约束
- ❌ 不要编造：资料里没有的时间、来源、数字一律不写
- ❌ 不要输出与历史基线重复的时间线节点
- ✅ 如果没有新信息，两个数组都返回空数组，`summary` 写「未发现新进展」
- ✅ `summary` 用一句话概括本轮进展，不超过 50 字

# 历史事件基线
{history}

# 本次检索到的最新资料
{findings}

# 今天的日期
{date}

# 输出（只输出 JSON，不要解释、不要代码块标记）
{{"summary": "...", "rumor_updates": [...], "timeline_updates": [...]}}
"""


